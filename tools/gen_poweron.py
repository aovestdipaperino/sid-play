#!/usr/bin/env python3
"""Decode the power-on RAM pattern table into crates/sid-gpl-data/src/poweron.rs.

Input is the run-length table published with the reference SID playback
library (GPL-2.0): records of [offset, [count], values], where a high bit on
the offset means a count byte follows, and a high bit on the count means the
next byte is repeated.
"""
import re, sys

src, dst = sys.argv[1], sys.argv[2]
data = []
for line in open(src, 'rb').read().split(b'\n'):
    line = re.sub(rb'/\*.*?\*/', b'', line)
    data += [int(x, 16) for x in re.findall(rb'0x([0-9a-fA-F]{2})', line)]

page = bytearray(0x400)
addr = i = 0
while i < len(data):
    off = data[i]; i += 1
    count, compressed = 0, False
    if off & 0x80:
        off &= 0x7f
        count = data[i]; i += 1
        if count & 0x80:
            count &= 0x7f
            compressed = True
    count += 1
    addr += off
    if compressed:
        v = data[i]; i += 1
        for _ in range(count):
            if addr < 0x400:
                page[addr] = v
            addr += 1
    else:
        for _ in range(count):
            if addr < 0x400:
                page[addr] = data[i]
            i += 1
            addr += 1

lines = [
    "//! Power-on RAM pattern for $0000-$03FF.",
    "//!",
    "//! Generated by tools/gen_poweron.py from the pattern published with the",
    "//! reference SID playback library, GPL-2.0. Written before the tune's init runs,",
    "//! because tunes read zero-page variables that a real machine leaves set.",
    "",
    "pub const POWERON: [u8; 0x0400] = [",
]
for r in range(0, 0x400, 16):
    lines.append("    " + ", ".join(str(b) for b in page[r:r + 16]) + ",")
lines.append("];")
open(dst, 'w').write("\n".join(lines) + "\n")
